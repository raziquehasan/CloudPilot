import assert from "node:assert/strict";
import test from "node:test";
import { createMetricsRegistry } from "@cloudpilot/metrics";
import type { Job } from "bullmq";
import type { QueueJob } from "@cloudpilot/queue";
import { createWorkerMetrics } from "../src/metrics-instruments.js";

test("worker metrics distinguish thrown retries and durable domain outcomes", async () => {
  const registry = createMetricsRegistry(false);
  const metrics = createWorkerMetrics(registry);
  assert.equal(createWorkerMetrics(registry), metrics);
  const job = { data: { kind: "runtime", action: "recover", deploymentId: "private-id" }, attemptsStarted: 1 } as Job<QueueJob>;
  const underlying = new Error("private failure");
  await assert.rejects(async () => metrics.wrap("runtime", async () => { throw underlying; })(job, undefined, undefined), (error) => error === underlying);
  job.attemptsStarted = 2;
  const result = { status: "failed" };
  assert.equal(await metrics.wrap("runtime", async () => result)(job, undefined, undefined), result);
  metrics.stalled("runtime");
  metrics.healthCheck(null, 0.01);
  metrics.healthCheck("HTTP_STATUS", 0.02);
  metrics.healthBatch("infrastructure_error", 0.03);
  metrics.recovery("MANUAL", "SUCCEEDED", null, 1);
  metrics.recovery("AUTOMATIC", "FAILED", "RECOVERY_RESTART_UNCERTAIN", 1);
  const output = await registry.metrics();
  assert.match(output, /attempt="first",outcome="error"\} 1/);
  assert.match(output, /attempt="subsequent",outcome="domain_failed"\} 1/);
  assert.match(output, /cloudpilot_worker_jobs_in_flight\{queue="runtime",job_type="recover",attempt="subsequent"\} 0/);
  assert.match(output, /cloudpilot_worker_job_stalls_total\{queue="runtime"\} 1/);
  assert.match(output, /cloudpilot_health_checks_total\{outcome="passed",reason="none"\} 1/);
  assert.match(output, /cloudpilot_health_checks_total\{outcome="failed",reason="HTTP_STATUS"\} 1/);
  assert.match(output, /cloudpilot_health_monitor_batches_total\{outcome="infrastructure_error"\} 1/);
  assert.match(output, /trigger="MANUAL",action="RESTART",outcome="SUCCEEDED"/);
  assert.match(output, /trigger="AUTOMATIC",action="RESTART",outcome="FAILED",reason="RECOVERY_RESTART_UNCERTAIN"/);
  assert.doesNotMatch(output, /private|trigger="AUTOMATIC",action="RESTART",outcome="SUCCEEDED"/);
  const counter = registry.getSingleMetric("cloudpilot_worker_jobs_total");
  assert.ok(counter && "inc" in counter);
  counter.inc = () => { throw new Error("Instrumentation error"); };
  const unchanged = { get status() { throw new Error("Unreadable observation"); } };
  assert.equal(await metrics.wrap("runtime", async () => unchanged)(job, undefined, undefined), unchanged);
});
